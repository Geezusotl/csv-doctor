"""Regenerate the sample data and RESULTS.md:  python -m benchmark.run"""
from __future__ import annotations

import json
from pathlib import Path

from csv_doctor.core import dumps

from .dataset import build
from .evaluate import evaluate
from .hard_cases import run_cases

HERE = Path(__file__).parent
HEADLINE_SEED = 7
SEEDS = range(1, 31)
RULE_ORDER = ["whitespace", "repeated_spaces", "missing_placeholder", "duplicate_row", "ragged_row", "mixed_date_format",
              "invalid_date", "number_format", "mixed_type", "outlier", "inconsistent_case", "category_typo", "spreadsheet_formula"]


def _pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def write_sample_data() -> None:
    ds = build(HEADLINE_SEED)
    data = HERE / "data"
    data.mkdir(exist_ok=True)
    (data / "clean.csv").write_text(dumps(ds.header, ds.clean), encoding="utf-8", newline="")
    (data / "dirty.csv").write_text(dumps(ds.header, ds.dirty), encoding="utf-8", newline="")
    key = [{"rule": t.rule, "row": t.row, "column": t.column, "original": t.original,
            "dirty": t.dirty, "expected_fix": t.expected_fix} for t in ds.truth]
    (data / "answer_key.json").write_text(json.dumps(key, indent=2) + "\n", encoding="utf-8")


def render() -> str:
    head = evaluate(HEADLINE_SEED)
    runs = [evaluate(s) for s in SEEDS]
    out = ["# Benchmark results", "",
           "Generated by `python -m benchmark.run`. Do not edit by hand.", "",
           "## How this is measured", "",
           "`benchmark/dataset.py` builds a clean 300-row people table, then injects a known set of "
           "errors into a copy and records each one (row, column, rule, and the value a perfect fixer "
           "would write). csv-doctor sees only the dirty file. A finding counts as correct only if "
           "its **rule, row and column** all match an injected error.", "",
           "**Read this with one caveat:** the same person wrote the generator and the checks, so each "
           "injected error is a kind the tool was built to find. These numbers show the pieces work "
           "together and don't regress. They are *not* a prediction of accuracy on your own files. "
           "The last section shows what happens on valid-but-tricky data.", "",
           f"## Headline run (seed {HEADLINE_SEED})", "",
           f"- Data rows in the dirty file: **{head['rows']}** (8 columns)",
           f"- Errors injected: **{head['injected']}**; reported by csv-doctor: **{head['reported']}**",
           f"- Precision: **{_pct(head['precision'])}**, recall: **{_pct(head['recall'])}** "
           f"({head['false_positives']} false positives, {head['missed']} missed)",
           f"- Suggested fixes: **{head['fix_correct']}** match what a perfect fixer writes, "
           f"{head['fix_not_offered']} declined to guess, {head['fix_wrong']} wrong",
           f"- Same checks on the original clean file: **{head['clean_file_findings']}** findings",
           f"- After `fix`: cells differing from the clean original went from **{head['cells_wrong_before']}** "
           f"to **{head['cells_wrong_after']}**; cells that were correct and got broken: "
           f"**{head['regressions']}**; good rows wrongly deleted: **{head['wrongly_deleted_rows']}**",
           "  (the remaining differences are blanks that cannot be restored, impossible dates, "
           "outliers and unreadable numbers, which are reported for a person to resolve)", "",
           "| Rule | Injected | Found | False positives |", "|---|---:|---:|---:|"]
    for rule in RULE_ORDER:
        c = head["per_rule"].get(rule, {})
        out.append(f"| {rule} | {c.get('injected', 0)} | {c.get('found', 0)} | {c.get('false_positives', 0)} |")

    n = len(runs)
    out += ["", f"## Stability across {n} random files (seeds {SEEDS.start}-{SEEDS.stop - 1})", "",
            f"- Precision: min {_pct(min(r['precision'] for r in runs))}, "
            f"mean {_pct(sum(r['precision'] for r in runs) / n)}",
            f"- Recall: min {_pct(min(r['recall'] for r in runs))}, "
            f"mean {_pct(sum(r['recall'] for r in runs) / n)}",
            f"- Wrong fix suggestions in total: {sum(r['fix_wrong'] for r in runs)}; "
            f"fixes declined because a date was ambiguous: {sum(r['fix_not_offered'] for r in runs)}",
            f"- Good cells broken by `fix`: {sum(r['regressions'] for r in runs)}; "
            f"good rows deleted: {sum(r['wrongly_deleted_rows'] for r in runs)}",
            f"- Clean files with at least one false alarm: "
            f"{sum(1 for r in runs if r['clean_file_findings'])} of {n}"
            + (f" (rules involved: {', '.join(sorted({x for r in runs for x in r['clean_file_rules']}))})"
               if any(r['clean_file_findings'] for r in runs) else ""), "",
            "## Valid data that still gets flagged (known limitations)", "",
            "Each case below is a column of *correct* values. Anything reported is a false positive.", "",
            "| Case | Result | Why it matters |", "|---|---|---|"]
    for case, rules in run_cases():
        result = "no findings" if not rules else "flagged: " + ", ".join(rules)
        out.append(f"| {case.name} | {result} | {case.note} |")
    out.append("")
    return "\n".join(out)


def main() -> None:
    write_sample_data()
    (HERE / "RESULTS.md").write_text(render(), encoding="utf-8")
    print(f"Wrote {HERE / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
